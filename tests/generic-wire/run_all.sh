#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../.."
generic_test_output="${1:-tests/generic-wire/out/checks}"
mkdir -p "$generic_test_output"
generic_test_output="$(realpath "$generic_test_output")"
generic_test_cc="${CC:-clang}"
generic_test_flags=(-std=c11 -O1 -g -Wall -Wextra -Werror -fsanitize=address,undefined -fno-omit-frame-pointer -I.)
generic_test_sources=(protocol_runtime.c generic_runtime.c generic_wire.c native_json.c protocol_codec_*.c)
export ASAN_OPTIONS="detect_leaks=1:abort_on_error=1"
export UBSAN_OPTIONS="halt_on_error=1:print_stacktrace=1"
python3 tests/generic-wire/test_profile_checker.py > "$generic_test_output/profile-checker.log" 2>&1
python3 tests/generic-wire/test_evidence_provenance.py > "$generic_test_output/evidence-provenance.log" 2>&1
python3 tools/check_generic_wire_profiles.py > "$generic_test_output/descriptions.json"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_generic_wire.c generic_wire.c native_json.c -o "$generic_test_output/wire"
"$generic_test_output/wire" tests/generic-wire/fictional_protocol.json > "$generic_test_output/wire.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_generic_profiles.c generic_wire.c native_json.c -o "$generic_test_output/profiles"
"$generic_test_output/profiles" protocols/*/generic_wire.json > "$generic_test_output/profiles.log"
for generic_test_name in runtime modbus; do
  "$generic_test_cc" "${generic_test_flags[@]}" "tests/generic-wire/test_generic_${generic_test_name}.c" "${generic_test_sources[@]}" -o "$generic_test_output/$generic_test_name"
done
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_generic_load.c "${generic_test_sources[@]}" -o "$generic_test_output/load"
"$generic_test_output/load" > "$generic_test_output/load.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_state_shared_bounds.c -o "$generic_test_output/state_bounds"
"$generic_test_output/state_bounds" > "$generic_test_output/state_bounds.log"
"$generic_test_cc" -O1 -g -Wno-pointer-sign -Wno-unused-result -I. -c aflnet.c -o "$generic_test_output/aflnet.o"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_message_context_lifecycle.c "$generic_test_output/aflnet.o" -o "$generic_test_output/lifecycle"
"$generic_test_output/lifecycle" > "$generic_test_output/lifecycle.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_observation_isolation.c -o "$generic_test_output/observation_isolation"
"$generic_test_output/observation_isolation" > "$generic_test_output/observation_isolation.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_transmission_ledger.c "$generic_test_output/aflnet.o" -o "$generic_test_output/ledger"
"$generic_test_output/ledger" > "$generic_test_output/ledger.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_state_observation_provider.c -o "$generic_test_output/state_observation_provider"
"$generic_test_output/state_observation_provider" > "$generic_test_output/state_observation_provider.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_candidate_metadata_identity.c -o "$generic_test_output/candidate_metadata"
"$generic_test_output/candidate_metadata" > "$generic_test_output/candidate_metadata.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_novelty_admission_decoupling.c -o "$generic_test_output/novelty_admission"
"$generic_test_output/novelty_admission" > "$generic_test_output/novelty_admission.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_reachability_deduplication.c -o "$generic_test_output/reachability_dedup"
"$generic_test_output/reachability_dedup" > "$generic_test_output/reachability_dedup.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_no_response_observation.c -o "$generic_test_output/no_response_obs"
"$generic_test_output/no_response_obs" > "$generic_test_output/no_response_obs.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_message_snapshot_boundary_mapping.c -o "$generic_test_output/boundary_mapping"
"$generic_test_output/boundary_mapping" > "$generic_test_output/boundary_mapping.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_target_state_m2_selection.c -o "$generic_test_output/target_state_m2"
"$generic_test_output/target_state_m2" > "$generic_test_output/target_state_m2.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_alias_canonical_identity.c "${generic_test_sources[@]}" -o "$generic_test_output/alias_canonical"
"$generic_test_output/alias_canonical" > "$generic_test_output/alias_canonical.log"
"$generic_test_cc" "${generic_test_flags[@]}" tests/generic-wire/test_ir_loader_contract.c "${generic_test_sources[@]}" -o "$generic_test_output/ir_contract"
"$generic_test_output/ir_contract" > "$generic_test_output/ir_contract.log"
"$generic_test_output/runtime" tests/generic-wire/fictional_protocol.json > "$generic_test_output/runtime.log"
"$generic_test_output/modbus" protocols/modbus_tcp/generic_wire.json > "$generic_test_output/modbus.log"
printf 'Generic C grammar/runtime checks passed. Logs: %s\n' "$generic_test_output"
